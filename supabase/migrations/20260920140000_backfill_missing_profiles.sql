-- ============================================================================
-- Чиним рассинхрон auth.users <-> public.users: у части аккаунтов (как
-- минимум у одного тестового, vvazakin@yandex.ru) при регистрации не
-- создалась строка в public.users — триггер handle_new_user должен был
-- это сделать, но по какой-то причине не сработал (или сработал с ошибкой,
-- которая не помешала самой регистрации). Так как Supabase создаёт запись
-- в auth.users только один раз, при самой первой регистрации, а не при
-- каждом клике по magic-link — если тогда триггер не сработал, починить
-- нечем: новых INSERT в auth.users для этого email больше не будет.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Разрешаем пользователю самому создать свою строку в public.users, если её
-- почему-то ещё нет — раньше INSERT был доступен только SECURITY DEFINER
-- триггеру, обычному authenticated-пользователю insert в эту таблицу был
-- запрещён (RLS). Это защитная мера на будущее — сама заявка на "чинку"
-- пойдёт через upsert в коде (см. saveHomeLocation), а не отдельный insert.
-- ----------------------------------------------------------------------------

create policy "users: insert own"
on public.users for insert
to authenticated
with check (id = auth.uid());

-- ----------------------------------------------------------------------------
-- Разово чиним уже сломанные аккаунты — создаём недостающие строки для
-- всех auth.users, у которых нет пары в public.users.
-- ----------------------------------------------------------------------------

insert into public.users (id, email)
select au.id, au.email
from auth.users au
left join public.users pu on pu.id = au.id
where pu.id is null;
