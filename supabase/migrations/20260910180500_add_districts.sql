-- ============================================================================
-- districts: справочник районов Москвы (из public/moscow-districts.geojson)
-- + district_id на users вместо хранения названия района строкой
-- ============================================================================

create table public.districts (
  id uuid primary key default gen_random_uuid(),
  -- id узла/отношения OSM (напр. "relation/226927") — стабильный внешний ключ
  -- для повторной синхронизации со справочником при обновлении geojson
  osm_id text not null unique,
  name text not null unique,
  created_at timestamptz not null default now()
);

comment on table public.districts is
  'Справочник районов Москвы, загружен из public/moscow-districts.geojson (OSM admin_level=8)';

